const iconEntries = Object.entries(icons);

export function getIcon(key: string) {
  let hash = 0;

  for (let i = 0; i < key.length; i++) {
    hash = (hash * 31 + key.charCodeAt(i)) >>> 0;
  }

  const [name, ascii] = iconEntries[hash % iconEntries.length];
  return { name, ascii };
}
